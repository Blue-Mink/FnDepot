def _to_png(img: Image.Image) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    return buf.getvalue()


def _paste_centered(icon_png: bytes, ratio: float) -> bytes:
    """把图标 PNG 缩放到 ratio 比例，居中贴到透明 512 画布。"""
    img = Image.new("RGBA", (SIZE, SIZE), (0, 0, 0, 0))
    icon = Image.open(io.BytesIO(icon_png)).convert("RGBA")
    w = max(1, int(SIZE * ratio))
    icon = icon.resize((w, w), Image.LANCZOS)
    img.alpha_composite(icon, ((SIZE - w) // 2, (SIZE - w) // 2))
    return _to_png(img)


