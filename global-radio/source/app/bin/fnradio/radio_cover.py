_tag_png_cache: dict[str, bytes] = {}


def tag_cover_png(tag: str = "") -> bytes:
    """标签分类歌单封面：按标签返回语义图标（懒渲染+缓存），未映射回退通用 tag 图标。"""
    icon = _tag_png_cache.get(tag)
    if icon is None:
        try:
            import cairosvg
            icon = cairosvg.svg2png(
                bytestring=_TAG_ICON_SVGS.get(tag, _TAG_FALLBACK_SVG).encode("utf-8"),
                output_width=SIZE, output_height=SIZE)
        except Exception:
            logger.exception("render tag icon failed: %s", tag)
            icon = b""
        if not icon:
            return _paste_centered(_TOWER_PNG, ICON_RATIO)
        _tag_png_cache[tag] = icon
    return _paste_centered(icon, ICON_RATIO)



def render_flag_svg(svg_bytes: bytes) -> bytes | None:
    """circle-flags SVG → 512 PNG（cairosvg，透明底圆形国旗）。失败返回 None。"""
    try:
        import cairosvg
        return cairosvg.svg2png(bytestring=svg_bytes, output_width=SIZE, output_height=SIZE)
    except Exception:
        logger.exception("render flag svg failed")
        return None


def data_url(png: bytes) -> str:
    return "data:image/png;base64," + base64.b64encode(png).decode()
